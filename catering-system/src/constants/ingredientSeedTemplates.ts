/**
 * ingredientSeedTemplates — Feature 041: 常用食材一鍵建檔
 *
 * 團膳常用食材範本。`marketCropName` 對應農業部 AMIS 農產品交易行情站的
 * 作物名稱（上游為子字串比對，故使用最短可辨識的名稱）。命名依 AMIS 慣例：
 * 高麗菜=甘藍、地瓜葉=甘藷葉、空心菜=蕹菜、小黃瓜=花胡瓜、大黃瓜=刺胡瓜、
 * 四季豆=敏豆、香菜=芫荽、青花菜=青花苔、白蘿蔔=蘿蔔、地瓜=甘藷。
 * 對應正確性以「市場行情 → 更新市價」實測為準：查無資料的品項請在
 * 食材主檔個別修正 marketCropName。
 *
 * `defaultPrice` 為粗略基準價（NT$/kg，供市價漲跌對照），請依實際採購價調整。
 * 肉類/主食/蛋豆製品不在果菜行情範圍，不設 marketCropName。
 */

export interface IngredientSeedTemplate {
  name: string;
  category: string;
  baseUnit: 'g' | 'ml' | 'pcs';
  purchaseUnit: string;
  conversionFactorToBaseUnit: number;
  defaultPrice: number;
  defaultPriceUnit: string;
  marketCropName?: string;
}

const kg = (
  name: string,
  category: string,
  defaultPrice: number,
  marketCropName?: string,
): IngredientSeedTemplate => ({
  name,
  category,
  baseUnit: 'g',
  purchaseUnit: 'kg',
  conversionFactorToBaseUnit: 1000,
  defaultPrice,
  defaultPriceUnit: 'kg',
  ...(marketCropName ? { marketCropName } : {}),
});

