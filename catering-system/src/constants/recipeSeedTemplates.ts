/**
 * recipeSeedTemplates — Feature 042: 配方草稿自動建立
 *
 * 常用團膳菜色配方範本。每道菜的 `bom` 為「每一份」的食材用量（公克），
 * `ingredientName` 必須對應食材主檔名稱（Feature 041 範本的 77 項）。
 * 用量為團膳常見值（先求有），請於配方管理個別微調。
 *
 * `aliases` 為同義菜名（比對時視為同一道菜）。
 */

export interface RecipeSeedBomItem {
  ingredientName: string;
  gramsPerServing: number;
}

export interface RecipeSeedTemplate {
  dishName: string;
  aliases?: string[];
  bom: RecipeSeedBomItem[];
}

const d = (
  dishName: string,
  bom: [string, number][],
  aliases?: string[],
): RecipeSeedTemplate => ({
  dishName,
  ...(aliases ? { aliases } : {}),
  bom: bom.map(([ingredientName, gramsPerServing]) => ({ ingredientName, gramsPerServing })),
});

